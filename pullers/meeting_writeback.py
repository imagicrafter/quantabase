"""Write Fireflies meeting pages into the knowledge repo, then record where.

Called by `pullers.fireflies.before_upsert` (daily run + self-heal sweep) and
by `pullers.backfill_meeting_pages`. Per page, `decide_action()` picks:

- **create**      -- no page yet.
- **regenerate**  -- a page this generator wrote (human `## ` sections kept),
                     or a page in the retired `fireflies_ingest.py` template.
- **skip**        -- anything else (hand-written or richer pages). Never overwritten.

Same-title same-day recordings (one bot per attendee) collapse to ONE page,
rendered from the longest transcript; every member's row points at it.

A page that differs from what is on disk only by its `updated`/`generated`
dates is left alone, so a re-fetched meeting does not commit every day. On an
existing generator page the stored `related` list is reused instead of asking
the model again, for the same reason.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from datetime import date, datetime, timedelta, timezone
from pathlib import Path
from typing import Any, Callable

from knowledge.engine_config import get_config
from knowledge.frontmatter import as_list, parse as parse_frontmatter
from pullers import fireflies_tags
from pullers.meeting_links import (
    MAX_RELATED,
    is_self,
    MeetingLinks,
    WikiIndex,
    build_index,
    build_links,
    default_llm,
    normalise,
)
from pullers.meeting_page import (
    GENERATOR,
    OWNED_HEADINGS,
    MeetingInput,
    render_meeting_page,
    today_utc,
)
from knowledge.kb_schema import db

MEETINGS_DIR = "meetings"
OLD_TEMPLATE_HEADINGS = frozenset({"Overview", "Action Items", "Keywords", "Attendees", "Source"})
SELF_HEAL_DAYS = 30
_VOLATILE = re.compile(r"^(updated: .*|  at: .*|Generated by .* on \d{4}-\d{2}-\d{2}\.)$", re.MULTILINE)


@dataclass
class WritebackReceipt:
    page_ids: dict[str, str] = field(default_factory=dict)   # external_id -> "meetings/<file>"
    written: list[str] = field(default_factory=list)
    unchanged: list[str] = field(default_factory=list)
    skipped: list[tuple[str, str]] = field(default_factory=list)
    commit: str = ""
    error: str | None = None
    previews: dict[str, str] = field(default_factory=dict)

    def summary(self) -> str:
        return (
            f"written={len(self.written)} unchanged={len(self.unchanged)} "
            f"skipped={len(self.skipped)} commit={self.commit or '-'}"
            + (f" error={self.error}" if self.error else "")
        )


def sections(page: str) -> list[tuple[str, str]]:
    """(`## ` heading, full section text including the heading line)."""
    text = page.split("\n---\n", 1)[1] if page.startswith("---\n") else page
    found: list[tuple[str, str]] = []
    matches = list(re.finditer(r"^## (.+)$", text, re.MULTILINE))
    for i, match in enumerate(matches):
        end = matches[i + 1].start() if i + 1 < len(matches) else len(text)
        found.append((match.group(1).strip(), text[match.start():end].strip()))
    return found


def is_generated(page: str) -> bool:
    return f'by: "{GENERATOR}"' in page.split("\n---\n", 1)[0]


def decide_action(existing: str | None) -> tuple[str, str]:
    if existing is None:
        return "create", "no page"
    if is_generated(existing):
        return "regenerate", "generator page"
    if is_old_template(existing):
        return "regenerate", "old fireflies_ingest template"
    return "skip", "hand-written or non-template page"


def is_old_template(page: str) -> bool:
    """The retired fireflies_ingest.py shape, and nothing a human would write:
    only its four/five headings, a fireflies_id, `related: []` (its matcher
    never linked anyone), and none of the OKF fields later writers add."""
    fm = parse_frontmatter(page).frontmatter
    names = {heading for heading, _ in sections(page)}
    return (
        bool(names) and names <= OLD_TEMPLATE_HEADINGS
        and bool(fm.get("fireflies_id"))
        and not as_list(fm.get("related"))
        and not any(key in fm for key in ("generated", "sources", "description"))
        and not fm.get("reviewed")  # a human signed off on this page: leave it
    )


def summary_from_old_page(existing: str) -> dict[str, Any]:
    """Overview / Action Items / Keywords from an old-template page, for meetings
    whose Fireflies notes are no longer retrievable."""
    found = {heading: text.split("\n", 1)[1].strip() if "\n" in text else "" for heading, text in sections(existing)}
    summary: dict[str, Any] = {}
    if found.get("Overview"):
        summary["overview"] = found["Overview"]
    if found.get("Action Items"):
        summary["action_items"] = found["Action Items"]
    if found.get("Keywords"):
        summary["keywords"] = [k.strip() for k in found["Keywords"].split(",") if k.strip()]
    return summary


def _strip_volatile(text: str) -> str:
    return _VOLATILE.sub("", text)


def _summary_text(summary: dict[str, Any]) -> str:
    keywords = summary.get("keywords") or []
    if isinstance(keywords, list):
        keywords = ", ".join(map(str, keywords))
    parts = [summary.get("short_summary"), summary.get("overview"), keywords]
    return "\n".join(str(p).strip() for p in parts if p)


def page_name_for(inp: MeetingInput) -> str:
    """Bare `{date}-{slug}.md` -- the filename every member of a duplicate group shares."""
    from pullers.fireflies import _external_id

    return _external_id(inp.title, inp.date_str)


def collapse(inputs: list[MeetingInput]) -> list[tuple[MeetingInput, list[MeetingInput]]]:
    """Group same-page recordings; keep the longest transcript. Returns
    (primary input, every member)."""
    groups: dict[str, list[MeetingInput]] = {}
    for inp in inputs:
        groups.setdefault(page_name_for(inp), []).append(inp)
    out: list[tuple[MeetingInput, list[MeetingInput]]] = []
    for members in groups.values():
        ranked = sorted(members, key=lambda m: (len(m.transcript_lines), bool(m.summary)), reverse=True)
        primary = ranked[0]
        if not primary.summary:
            donor = next((m for m in ranked if m.summary), None)
            if donor:
                primary = MeetingInput(**{**_fields(primary), "summary": donor.summary})
        out.append((primary, members))
    return out


_FIREFLIES_ID_LINE = re.compile(r'^fireflies_id: *"?([A-Za-z0-9]+)"?\s*$', re.MULTILINE)


def pages_by_fireflies_id(root: Path) -> dict[str, list[str]]:
    """fireflies_id -> every "meetings/<file>" page carrying it.

    Older pages were named from the CALENDAR title, Fireflies rows from the
    Fireflies title, so the same meeting can sit under two names. The id in
    the page's frontmatter is the reliable join -- except that the retired
    writer sometimes stamped one recording onto two calendar events, so an id
    can map to several pages; `resolve_page` picks among them.
    """
    found: dict[str, list[str]] = {}
    folder = root / MEETINGS_DIR
    for path in sorted(folder.glob("*.md")) if folder.exists() else []:
        try:
            head = path.read_text(encoding="utf-8")[:3000]
        except (OSError, UnicodeDecodeError):
            continue
        match = _FIREFLIES_ID_LINE.search(head.split("\n---", 2)[0] if head.startswith("---") else "")
        if match:
            found.setdefault(match.group(1), []).append(f"{MEETINGS_DIR}/{path.name}")
    return found


def resolve_page(root: Path, primary: MeetingInput, members: list[MeetingInput],
                 by_fid: dict[str, list[str]]) -> str:
    """Pick the existing page for this recording.

    1. A page named exactly for the Fireflies title/date (or the stored
       external_id) wins -- even over another page carrying the same id, which
       is how a mis-stamped calendar duplicate is told apart from the real one.
    2. Otherwise the page carrying the fireflies_id (renamed calendar title).
    3. Otherwise the bare name (new page).
    """
    exact = [f"{MEETINGS_DIR}/{page_name_for(primary)}", f"{MEETINGS_DIR}/{primary.external_id}"]
    for rel in exact:
        if (root / rel).exists():
            return rel
    for member in [primary, *members]:
        candidates = by_fid.get(member.fireflies_id or "", [])
        if candidates:
            same_day = [c for c in candidates if Path(c).name[:10] == primary.date_str]
            return (same_day or candidates)[0]
    return exact[0]


def _fields(inp: MeetingInput) -> dict[str, Any]:
    return {name: getattr(inp, name) for name in MeetingInput.__slots__}


def _merge_people(stored: tuple[str, ...], links: MeetingLinks) -> tuple[str, ...]:
    """Keep the stored `related` list, adding attendees who match a page now
    (e.g. after an alias was added) but did not when the list was made."""
    people = tuple(
        link for display, link in links.attendees
        if link and link not in stored
        and not is_self(display) and not is_self(link[2:-2])
    )
    return (stored + tuple(dict.fromkeys(people)))[:MAX_RELATED]


def _render_one(
    inp: MeetingInput,
    existing: str | None,
    action: str,
    index: WikiIndex,
    today: date,
    llm: Callable[[str], str] | None,
) -> str:
    created = None
    extra = ""
    if existing is not None:
        fm = parse_frontmatter(existing).frontmatter
        created = str(fm.get("created") or "") or None
        body = parse_frontmatter(existing).body
        preamble = body.split("\n## ", 1)[0].strip() if not body.lstrip().startswith("## ") else ""
        extra = "\n\n".join(
            [f"## Notes Before Regeneration\n\n{preamble}"] if preamble and is_generated(existing) else []
            + [text for heading, text in sections(existing) if heading not in OWNED_HEADINGS]
        )
        if not inp.summary and action == "regenerate":
            inp = MeetingInput(**{**_fields(inp), "summary": summary_from_old_page(existing)})

    reuse_related = existing is not None and is_generated(existing)
    links: MeetingLinks = build_links(
        title=inp.title,
        summary_text=_summary_text(inp.summary),
        speakers=inp.speakers,
        emails=inp.attendee_emails,
        index=index,
        llm=None if reuse_related else llm,
    )
    related = links.related
    if reuse_related:
        stored = tuple(as_list(parse_frontmatter(existing).frontmatter.get("related")))
        related = _merge_people(stored, links) if stored else related

    topics_key = get_config().tagging.frontmatter_key
    return render_meeting_page(
        inp,
        attendees=links.attendees,
        related=related,
        today=today,
        created=created,
        extra_sections=extra if action == "regenerate" and is_generated(existing or "") else "",
        topics=fireflies_tags.page_topics(existing, inp.page_topics, topics_key),
        topics_key=topics_key,
    )


def write_pages(
    inputs: list[MeetingInput],
    *,
    root: Path | None = None,
    today: date | None = None,
    llm: Callable[[str], str] | None = default_llm,
    dry_run: bool = False,
    push: bool = True,
    message: str | None = None,
) -> WritebackReceipt:
    from pullers import knowledge_repo

    receipt = WritebackReceipt()
    if not inputs:
        return receipt
    today = today or today_utc()
    root = root or knowledge_repo.resolve_root()
    index = build_index(root)
    by_fid = pages_by_fireflies_id(root)
    pending: dict[str, list[str]] = {}

    for primary, group in collapse(inputs):
        rel = resolve_page(root, primary, group, by_fid)
        members = [m.external_id for m in group]
        path = root / rel
        existing = path.read_text(encoding="utf-8") if path.exists() else None
        action, reason = decide_action(existing)

        if action == "skip":
            receipt.skipped.append((rel, reason))
            for external_id in members:
                receipt.page_ids[external_id] = rel  # the page exists; it just is not ours
            continue

        page = _render_one(primary, existing, action, index, today, llm)
        published = not push or dry_run or knowledge_repo.on_main(root, rel)
        if existing is not None and published and _strip_volatile(existing) == _strip_volatile(page):
            receipt.unchanged.append(rel)
            for external_id in members:
                receipt.page_ids[external_id] = rel
            continue

        if dry_run:
            receipt.previews[rel] = page
            receipt.written.append(rel)
            continue

        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(page, encoding="utf-8")
        receipt.written.append(rel)
        pending[rel] = members

    if dry_run or not pending:
        return receipt

    if not push:
        for rel, members in pending.items():
            for external_id in members:
                receipt.page_ids[external_id] = rel
        return receipt

    try:
        receipt.commit = knowledge_repo.commit_and_push(
            root,
            sorted(pending),
            message or f"wiki(auto): meetings {today.isoformat()} — {len(pending)} page(s)",
        )
        for rel, members in pending.items():
            for external_id in members:
                receipt.page_ids[external_id] = rel
    except knowledge_repo.KnowledgeRepoError as error:
        receipt.error = str(error)
    return receipt


def self_heal_rows(sb, *, days: int = SELF_HEAL_DAYS, exclude: set[str] | None = None) -> list[dict]:
    """Recent fireflies parent rows with no wiki page recorded yet."""
    cutoff = (datetime.now(timezone.utc) - timedelta(days=days)).isoformat()
    resp = (
        db(sb).table("documents")
        .select("external_id,title,body,metadata,domains,source_created_at")
        .eq("source", "fireflies").is_("parent_external_id", "null").is_("deleted_at", "null")
        .gte("source_created_at", cutoff).execute()
    )
    exclude = exclude or set()
    return [
        row for row in resp.data or []
        if row["external_id"] not in exclude and not (row.get("metadata") or {}).get("wiki_page_id")
    ]


def patch_page_ids(sb, page_ids: dict[str, str]) -> int:
    """Set metadata.wiki_page_id on stored rows (metadata-only; never touches
    `embedding` -- same single-row `.update()` discipline as ingest._patch_rows)."""
    patched = 0
    for external_id, page_id in page_ids.items():
        rows = (
            db(sb).table("documents").select("metadata")
            .eq("source", "fireflies").eq("external_id", external_id).limit(1).execute().data
        )
        if not rows:
            continue
        metadata = rows[0].get("metadata") or {}
        if metadata.get("wiki_page_id") == page_id:
            continue
        (
            db(sb).table("documents")
            .update({"metadata": {**metadata, "wiki_page_id": page_id}})
            .eq("source", "fireflies").eq("external_id", external_id).execute()
        )
        patched += 1
    return patched


def stored_page_ids(sb, external_ids: list[str]) -> dict[str, str]:
    """The `metadata.wiki_page_id` already recorded for the given fireflies rows.

    A re-index rebuilds every document with `wiki_page_id = None`; carrying the
    stored value back in (see `fireflies.keep_stored_page_ids`) means a run whose
    wiki write-back failed never clears a link a previous run recorded.
    """
    if not external_ids:
        return {}
    found: dict[str, str] = {}
    for start in range(0, len(external_ids), 100):
        chunk = external_ids[start:start + 100]
        resp = (
            db(sb).table("documents")
            .select("external_id,metadata")
            .eq("source", "fireflies").in_("external_id", chunk).execute()
        )
        for row in resp.data or []:
            page = (row.get("metadata") or {}).get("wiki_page_id")
            if isinstance(page, str) and page:
                found[row["external_id"]] = page
    return found
